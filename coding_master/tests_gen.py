"""Generate runnable unit tests from a Python module's AST.

The generated suite always passes on a syntactically valid module: it checks
availability, signatures and public methods, and marks behaviour tests as
skipped placeholders. That gives a real, executable starting point instead of
failing tests.
"""

import ast
import os

from . import util


def _signature(node):
    parts = []
    args = node.args
    positional = list(args.posonlyargs) + list(args.args)
    defaults = list(args.defaults)
    offset = len(positional) - len(defaults)
    for index, arg in enumerate(positional):
        text = arg.arg
        if arg.annotation is not None:
            text += ": " + ast.unparse(arg.annotation)
        if index >= offset:
            text += " = " + ast.unparse(defaults[index - offset])
        parts.append(text)
    if args.vararg:
        parts.append("*" + args.vararg.arg)
    elif args.kwonlyargs:
        parts.append("*")
    for arg, default in zip(args.kwonlyargs, args.kw_defaults):
        text = arg.arg
        if arg.annotation is not None:
            text += ": " + ast.unparse(arg.annotation)
        if default is not None:
            text += " = " + ast.unparse(default)
        parts.append(text)
    if args.kwarg:
        parts.append("**" + args.kwarg.arg)
    return "(%s)" % ", ".join(parts)


def _required_parameters(node):
    args = node.args
    positional = list(args.posonlyargs) + list(args.args)
    required = positional[: len(positional) - len(args.defaults)]
    required += [arg for arg, default in zip(args.kwonlyargs, args.kw_defaults)
                 if default is None]
    return [arg.arg for arg in required]


class TestGenerator:
    """Build unittest (or pytest) suites for local Python modules."""

    def __init__(self, root):
        self.root = os.path.abspath(root)

    def inspect_module(self, path):
        text = util.read_text(path)
        tree = ast.parse(text, filename=path)
        functions = []
        classes = []
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if node.name.startswith("_"):
                    continue
                functions.append({
                    "name": node.name,
                    "signature": _signature(node),
                    "required": _required_parameters(node),
                    "async": isinstance(node, ast.AsyncFunctionDef),
                    "line": node.lineno,
                })
            elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
                methods = [child.name for child in node.body
                           if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef))
                           and not child.name.startswith("_")]
                init = next((child for child in node.body
                             if isinstance(child, ast.FunctionDef)
                             and child.name == "__init__"), None)
                required = _required_parameters(init) if init is not None else []
                classes.append({
                    "name": node.name,
                    "methods": methods,
                    "required": required,
                    "line": node.lineno,
                })
        return {"functions": functions, "classes": classes}

    def _module_name(self, path):
        relative = util.relpath(self.root, path)
        if relative.endswith(".py"):
            relative = relative[:-3]
        relative = relative.replace("/", ".")
        if relative.endswith(".__init__"):
            relative = relative[: -len(".__init__")]
        return relative

    def generate(self, path, framework="unittest", module=None,
                 bootstrap=True):
        info = self.inspect_module(path)
        module = module or self._module_name(path)
        package = module.split(".")[0]
        lines = []
        lines.append('"""Tests for %s - generated by ULTIMATE CODING MASTER.'
                     % module)
        lines.append("")
        lines.append("Run locally: python -m unittest discover -s tests -v")
        lines.append('"""')
        lines.append("")

        if bootstrap:
            lines.append("import os")
            lines.append("import sys")
            lines.append("")
            lines.append("_ROOT = os.path.dirname(os.path.dirname("
                         "os.path.abspath(__file__)))")
            lines.append("if _ROOT not in sys.path:")
            lines.append("    sys.path.insert(0, _ROOT)")
            lines.append("")

        lines.append("import inspect")
        lines.append("import unittest")
        lines.append("")
        if module.count(".") == 0:
            lines.append("import %s" % module)
        else:
            lines.append("import %s" % module)
        lines.append("")

        test_count = 0

        for function in info["functions"]:
            class_name = "Test%s" % function["name"][:1].upper() + \
                         function["name"][1:].replace("_", "")
            lines.append("")
            lines.append("class %s(unittest.TestCase):" % class_name)
            lines.append('    """Smoke tests for %s.%s."""'
                         % (module, function["name"]))
            lines.append("")
            lines.append("    def test_is_callable(self):")
            lines.append("        self.assertTrue(callable(%s.%s))"
                         % (module, function["name"]))
            test_count += 1
            lines.append("")
            lines.append("    def test_signature(self):")
            lines.append("        parameters = list(inspect.signature("
                         "%s.%s).parameters)" % (module, function["name"]))
            expected = function["required"]
            if expected:
                lines.append("        self.assertEqual(parameters[:%d], %r)"
                             % (len(expected), expected))
            else:
                lines.append("        self.assertIsInstance(parameters, list)")
            test_count += 1
            lines.append("")
            lines.append('    @unittest.skip("replace with behaviour assertions")')
            lines.append("    def test_behaviour(self):")
            lines.append('        self.fail("behaviour test not written yet")')
            test_count += 1

        for klass in info["classes"]:
            lines.append("")
            lines.append("class Test%s(unittest.TestCase):" % klass["name"])
            lines.append('    """Smoke tests for %s.%s."""'
                         % (module, klass["name"]))
            lines.append("")
            lines.append("    def test_is_class(self):")
            lines.append("        self.assertTrue(inspect.isclass(%s.%s))"
                         % (module, klass["name"]))
            test_count += 1
            if klass["methods"]:
                lines.append("")
                lines.append("    def test_public_methods(self):")
                for method in klass["methods"]:
                    lines.append("        self.assertTrue(callable(getattr("
                                 "%s.%s, %r)))"
                                 % (module, klass["name"], method))
                test_count += 1
            if not klass["required"]:
                lines.append("")
                lines.append("    def test_instantiation(self):")
                lines.append("        instance = %s.%s()"
                             % (module, klass["name"]))
                lines.append("        self.assertIsNotNone(instance)")
                test_count += 1

        if not info["functions"] and not info["classes"]:
            lines.append("")
            lines.append("class TestModule(unittest.TestCase):")
            lines.append('    """Fallback test: the module imports cleanly."""')
            lines.append("")
            lines.append("    def test_import(self):")
            lines.append("        self.assertIsNotNone(%s)" % package)
            test_count += 1

        lines.append("")
        lines.append("")
        lines.append('if __name__ == "__main__":')
        lines.append("    unittest.main()")
        lines.append("")

        content = "\n".join(lines)
        return {
            "module": module,
            "framework": framework,
            "functions": len(info["functions"]),
            "classes": len(info["classes"]),
            "tests": test_count,
            "content": content,
            "lines": util.count_lines(content),
        }

    def write(self, path, output_path, framework="unittest", module=None):
        result = self.generate(path, framework=framework, module=module)
        util.write_text(output_path, result["content"])
        result["path"] = output_path
        return result
